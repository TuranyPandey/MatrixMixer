export const FONT_HEIGHT = 7;

/** 3x5 digits for compact readouts (clock, timers). Rows top to bottom, 3 bits each. */
const TINY: Record<string, readonly number[]> = {
  '0': [0b111, 0b101, 0b101, 0b101, 0b111],
  '1': [0b010, 0b110, 0b010, 0b010, 0b111],
  '2': [0b111, 0b001, 0b111, 0b100, 0b111],
  '3': [0b111, 0b001, 0b111, 0b001, 0b111],
  '4': [0b101, 0b101, 0b111, 0b001, 0b001],
  '5': [0b111, 0b100, 0b111, 0b001, 0b111],
  '6': [0b111, 0b100, 0b111, 0b101, 0b111],
  '7': [0b111, 0b001, 0b010, 0b010, 0b010],
  '8': [0b111, 0b101, 0b111, 0b101, 0b111],
  '9': [0b111, 0b101, 0b111, 0b001, 0b111],
  '%': [0b101, 0b001, 0b010, 0b100, 0b101],
  '-': [0b000, 0b000, 0b111, 0b000, 0b000],
  ' ': [0, 0, 0, 0, 0],
};
export const TINY_HEIGHT = 5;

/** A rendered line of text: `columns[x]` is a bitmask of lit rows, bit 0 = top. */
export type TextStrip = { width: number; height: number; columns: number[] };

function glyphColumns(ch: string): number[] {
  let code = ch.charCodeAt(0);
  if (code < 32 || code > 126) code = 63; // '?' for anything outside ASCII
  if (code === 32) return [0, 0, 0];
  const base = (code - 32) * 5;
  const cols = FONT_5X7.slice(base, base + 5);
  // Proportional spacing: drop empty columns on both sides.
  let start = 0;
  let end = cols.length;
  while (start < end && cols[start] === 0) start++;
  while (end > start && cols[end - 1] === 0) end--;
  return cols.slice(start, end);
}

/** Renders text in the 5x7 font into one long strip, one blank column between letters. */
export function renderText(text: string): TextStrip {
  const columns: number[] = [];
  for (const ch of text) {
    if (columns.length > 0) columns.push(0);
    columns.push(...glyphColumns(ch));
  }
  return { width: columns.length, height: FONT_HEIGHT, columns };
}

/** Renders digits and `:` in the 3x5 font. Unknown characters become blanks. */
export function renderTiny(text: string): TextStrip {
  const columns: number[] = [];
  for (const ch of text) {
    if (columns.length > 0) columns.push(0);
    if (ch === ':') {
      columns.push(0b01010);
      continue;
    }
    const rows = TINY[ch] ?? TINY[' ']!;
    for (let x = 0; x < 3; x++) {
      let col = 0;
      for (let y = 0; y < TINY_HEIGHT; y++) if (rows[y]! & (0b100 >> x)) col |= 1 << y;
      columns.push(col);
    }
  }
  return { width: columns.length, height: TINY_HEIGHT, columns };
}

/** Draws a strip onto a frame with its left edge at `x` and top at `y`. Clips at the edges. */
export function drawStrip(frame: Frame, strip: TextStrip, x: number, y: number, brightness = 255): void {
  for (let cx = 0; cx < strip.width; cx++) {
    const fx = x + cx;
    if (fx < 0 || fx >= SIZE) continue;
    const col = strip.columns[cx]!;
    for (let cy = 0; cy < strip.height; cy++) {
      if (col & (1 << cy)) setPixel(frame, fx, y + cy, brightness);
    }
  }
}

/** Draws a strip centred horizontally at row `y`. */
export function drawCentered(frame: Frame, strip: TextStrip, y: number, brightness = 255): void {
  drawStrip(frame, strip, Math.round((SIZE - strip.width) / 2), y, brightness);
}

/** Number of steps one full scroll takes: in from the right edge, out past the left. */
export function scrollLength(strip: TextStrip): number {
  return strip.width + SIZE;
}

/**
 * One frame of scrolling text. `step` 0 has the text just off the right edge.
 * Text is vertically centred, where the circular matrix is a full 25 wide.
 */
export function scrollFrame(strip: TextStrip, step: number, brightness = 255): Frame {
  const frame = blankFrame();
  const y = Math.floor((SIZE - strip.height) / 2);
  drawStrip(frame, strip, SIZE - (step % scrollLength(strip)), y, brightness);
  return frame;
}

/** Short text that fits in 25 columns is shown still and centred; longer text must scroll. */
export function fitsWithoutScrolling(strip: TextStrip): boolean {
  return strip.width <= SIZE;
}

export function staticTextFrame(strip: TextStrip, brightness = 255): Frame {
  const frame = blankFrame();
  drawCentered(frame, strip, Math.floor((SIZE - strip.height) / 2), brightness);
  return frame;
}
